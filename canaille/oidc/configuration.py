import datetime
from typing import Literal

from pydantic import model_validator

from canaille.app.configuration import BaseModel
from canaille.app.configuration import CommaSeparatedList


class UserInfoMappingSettings(BaseModel):
    """Mapping between the user model and the JWT fields.

    Fields are evaluated with jinja.
    A ``user`` var is available.
    """

    SUB: str | None = "{{ user.user_name }}"
    NAME: str | None = (
        "{% if user.formatted_name %}{{ user.formatted_name }}{% endif %}"
    )
    PHONE_NUMBER: str | None = (
        "{% if user.phone_numbers %}{{ user.phone_numbers[0] }}{% endif %}"
    )
    EMAIL: str | None = (
        "{% if user.preferred_email %}{{ user.preferred_email }}{% endif %}"
    )
    GIVEN_NAME: str | None = "{% if user.given_name %}{{ user.given_name }}{% endif %}"
    FAMILY_NAME: str | None = (
        "{% if user.family_name %}{{ user.family_name }}{% endif %}"
    )
    PREFERRED_USERNAME: str | None = (
        "{% if user.display_name %}{{ user.display_name }}{% endif %}"
    )
    LOCALE: str | None = (
        "{% if user.preferred_language %}{{ user.preferred_language }}{% endif %}"
    )
    ADDRESS: str | None = (
        "{% if user.formatted_address %}{{ user.formatted_address }}{% endif %}"
    )
    PICTURE: str | None = (
        "{% if user.photo %}{{ user | photo_url(external=True) }}{% endif %}"
    )
    WEBSITE: str | None = "{% if user.profile_url %}{{ user.profile_url }}{% endif %}"
    UPDATED_AT: str | None = (
        "{% if user.last_modified %}{{ user.last_modified.timestamp() }}{% endif %}"
    )


class OIDCSettings(BaseModel):
    """OpenID Connect settings.

    Belong in the ``CANAILLE_OIDC`` namespace.
    """

    ENABLE_OIDC: bool = True
    """Whether the Single Sign-On feature and the OpenID Connect API is enabled."""

    DYNAMIC_CLIENT_REGISTRATION_OPEN: bool = False
    """Whether a token is needed for the RFC7591 dynamical client registration.

    If :py:data:`True`, no token is needed to register a client.
    If :py:data:`False`, dynamical client registration requires a valid JWT token
    generated by the ``canaille jwt registration`` command.

    This only covers the registration of new clients. Reading, updating or
    deleting the registration of an existing client always requires the
    management token that was issued to that client.
    """

    REQUIRE_NONCE: bool = True
    """Force the nonce exchange during the authentication flows.

    This adds security but may not be supported by all clients.
    """

    ACTIVE_JWKS: list[dict[str, str] | str] | None = None
    """The active JSON Web Keys Set.

    Those keys are used to sign and verify JWTs.
    The keys can be in the form of JWK dict or raw keys."""

    INACTIVE_JWKS: list[dict[str, str] | str] | None = None
    """The inactive JSON Web Keys Set.

    Those keys are only used to verify JWTs.
    The keys can be in the form of JWK dict or raw keys."""

    ACCESS_TOKEN_TYPE: Literal["jwt", "plain"] = "jwt"
    """The format of the access tokens.

    - ``jwt``: signed :rfc:`JWT access tokens <9068>`.
      Resource servers can check them with the server public keys,
      but they do not see revoked tokens until the tokens expire.
    - ``plain``: random strings.
      Resource servers must check them with the
      :rfc:`introspection endpoint <7662>`, and see revoked tokens immediately.
      The clients and the resource servers cannot read anything in the tokens.
    """

    ACCESS_TOKEN_LIFETIME: datetime.timedelta = datetime.timedelta(hours=1)
    """The validity period of the access tokens.

    Clients can get new access tokens with their refresh tokens.
    Should be provided in ISO8601 duration format (e.g., "PT1H" for 1 hour)."""

    REFRESH_TOKEN_LIFETIME: datetime.timedelta = datetime.timedelta(days=10)
    """The validity period of the refresh tokens.

    Each refresh gives a new refresh token, so the period starts again.
    A change applies to the refresh tokens already issued.
    Should be provided in ISO8601 duration format (e.g., "P10D" for 10 days)."""

    TRUSTED_DOMAINS: CommaSeparatedList = [".localhost", "127.0.0.1"]
    """Trusted domains for automatic client trust.

    Clients with a :attr:`~canaille.oidc.basemodels.Client.client_uri` matching
    these domains will be automatically considered as trusted and will not
    display the consent page to users.
    This is particularly useful for development environments.

    Supports these patterns:

    - Exact match: ``example.com`` matches ``example.com``
    - Wildcard match: ``.example.com`` matches ``example.com`` and all its subdomains

    Examples:

    - ``[".localhost", "127.0.0.1"]`` (default for development)
    - ``[".dev.company.com", "staging.company.com"]``
    - ``[".local", "localhost"]``
    """

    USERINFO_MAPPING: UserInfoMappingSettings | None = UserInfoMappingSettings()
    """"Attribute mapping used to build an OIDC UserInfo object.

    UserInfo is used to fill the id_token and the userinfo endpoint."""

    DEVICE_CODE_LIFETIME: datetime.timedelta = datetime.timedelta(minutes=30)
    """The validity period of the ``device_code`` and ``user_code`` issued by the
    :rfc:`Device Authorization Grant <8628>` endpoint.

    Should be provided in ISO8601 duration format (e.g., "PT30M" for 30 minutes)."""

    DEVICE_CODE_POLLING_INTERVAL: datetime.timedelta = datetime.timedelta(seconds=5)
    """The minimum delay a device client should wait between two polling requests to
    the token endpoint during the :rfc:`Device Authorization Grant <8628>`.

    Should be provided in ISO8601 duration format (e.g., "PT5S" for 5 seconds)."""

    DEVICE_USER_CODE_TYPE: Literal["string", "digital"] = "string"
    """The kind of ``user_code`` generated for the
    :rfc:`Device Authorization Grant <8628>`.

    ``string`` produces codes like ``WDJB-MJHT`` (letters), while ``digital``
    produces codes like ``019-450-730`` (digits only)."""

    @model_validator(mode="after")
    def validate_device_code_durations(self):
        if self.DEVICE_CODE_POLLING_INTERVAL < datetime.timedelta(seconds=1):
            raise ValueError(
                "DEVICE_CODE_POLLING_INTERVAL must be at least one second."
            )

        if self.DEVICE_CODE_LIFETIME <= self.DEVICE_CODE_POLLING_INTERVAL:
            raise ValueError(
                "DEVICE_CODE_LIFETIME must be longer than DEVICE_CODE_POLLING_INTERVAL."
            )

        return self

    @model_validator(mode="after")
    def validate_token_lifetimes(self):
        if self.ACCESS_TOKEN_LIFETIME < datetime.timedelta(seconds=1):
            raise ValueError("ACCESS_TOKEN_LIFETIME must be at least one second.")

        if self.REFRESH_TOKEN_LIFETIME < datetime.timedelta(seconds=1):
            raise ValueError("REFRESH_TOKEN_LIFETIME must be at least one second.")

        return self

    @model_validator(mode="after")
    def validate_rsa_key_present(self):
        if self.ACTIVE_JWKS is not None:
            from canaille.oidc.jose import has_rsa_key

            if not has_rsa_key(self.ACTIVE_JWKS):
                raise ValueError(
                    "OIDC specification requires RS256 support. "
                    "Please configure at least one RSA key in ACTIVE_JWKS."
                )
        return self
